# Basic text print
print("Hello, World!")

# Print My name
print("Islamul Hoque Ishfak")

# Print numbers
print(123)
print(3.1416)

# Print multiple values together
print("My age is:", 22)

# Print expressions
print("Sum of 5 + 7 =", 5 + 7)

# Using f-string for formatted output
name = "Ishfak"
goal = "CEO of Google"
print(f"{name} will be {goal}, In-sha-allah")

# Escape characters
print("Line1\nLine2")   # newline
print("Tab\tSpace")     # tab

# Custom separator and end
print("Python", "is", "fun", sep="-")
print("Hello", end=" ")
print("World")
