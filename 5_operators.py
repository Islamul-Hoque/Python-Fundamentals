# Arithmetic Operators
a = 10
b = 3
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Exponent:", a ** b)

print("\n")

# Comparison Operators
x = 5
y = 8
print("x =", x, "y =", y)   # values first
print("x > y:", x > y)
print("x >= y:", x >= y)
print("x < y:", x < y)
print("x <= y:", x <= y)
print("x == y:", x == y)
print("x != y:", x != y)

print("\n")

# Logical Operators
p = True
q = False
print("p =", p, "q =", q)   # values first
print("p and q:", p and q)
print("p or q:", p or q)
print("not p:", not p)
