# Basic variable assignment
name = "Ishfak"
age = 22
print("Name:", name)
print("Age:", age)

# Different data types
x = 10          # int
y = 3.14        # float
s = "Python"    # string
flag = True     # boolean
print(x, y, s, flag)

# Update variable values
count = 5
print("Before update:", count)
count = count + 1
print("After update:", count)

# Multiple assignment
a, b, c = 1, 2, 3
print("Multiple assignment:", a, b, c)

# Type checking
value = 10.5
print("Value:", value, "Type:", type(value))

# Dynamic typing
var = "Hello"
print("Dynamic typing example:", var, "Type :", type(var))
var = 123
print("Now var is:", var, "Type:", type(var))
